// Audits the bundled Lichess puzzles with Stockfish 19 and writes PUZZLE-AUDIT.md
// plus research/puzzle-audit.json.
//
// For every one of your moves in every puzzle it checks that the puzzle's answer
// is Stockfish's best move (or as good as it: the same mate, or within 2 points of
// winning chance), and that the final position really is won (or, for "equality"
// puzzles, saved). Lichess has already checked its puzzles with Stockfish and with
// millions of players' attempts; this repeats the engine check on our copy.
//
// Puzzles flagged by the first pass are searched again more deeply; any that still
// fail are written to js/puzzles-exclude.js, and the Puzzles mode skips them.
//
// Usage: node tools/audit-puzzles.js [--workers 8] [--depth 14] [--deep 22] [--limit N]
const path = require('path');
const fs = require('fs');

global.window = global;
global.self = global;
require('../js/puzzles-data.js');
const Core = require('../js/core.js')();
const coach = require('../js/coach.js')(Core);
const { makePool } = require('./stockfish-pool.js');

const arg = (name, def) => { const i = process.argv.indexOf('--' + name); return i > 0 ? +process.argv[i + 1] : def; };
const WORKERS = arg('workers', 8), DEPTH = arg('depth', 14), DEEP = arg('deep', 22), LIMIT = arg('limit', 0);

// How much winning chance the final position must give you. Lichess tags a puzzle
// "equality" (you save the game), "advantage" (you end clearly better) or
// "crushing"/mate (you end winning).
const need = (tags) => (tags.includes('equality') ? 35 : tags.includes('advantage') ? 60 : 65);

(async function main() {
  const t0 = Date.now();
  const { themes, puzzles } = window.MYCHESS_PUZZLES;
  const list = LIMIT ? puzzles.slice(0, LIMIT) : puzzles;
  const pool = await makePool(WORKERS, Core);
  const results = [];
  let done = 0;
  async function check([id, fen, moves, rating, themeIdx], depth) {
    const tags = themeIdx.map((i) => themes[i]);
    const ucis = moves.split(' ');
    const pos = new Core.Position(fen);
    pos.make(pos.moveFromUci(ucis[0])); // the opponent's setup move
    const solver = pos.side;
    const steps = [];
    for (let i = 1; i < ucis.length; i++) {
      const before = pos.toFEN();
      pos.make(pos.moveFromUci(ucis[i]));
      if (i % 2 === 1) steps.push({ before, after: pos.toFEN(), uci: ucis[i], mate: pos.inCheck() && !pos.legalMoves().length });
    }
    const issues = [];
    for (const s of steps) {
      if (s.mate) continue; // checkmate always solves it
      const b = await pool.analyse(s.before, depth);
      if (b.best === s.uci) continue;
      const a = await pool.analyse(s.after, depth);
      const loss = Math.max(0, coach.winPct(b.score) - (100 - coach.winPct(a.score)));
      const sameMate = b.score.mate > 0 && a.score.mate < 0 && -a.score.mate <= b.score.mate;
      if (loss > 2 && !sameMate) issues.push(`move ${s.uci}: Stockfish prefers ${b.best} (the answer gives away ${loss.toFixed(1)} points)`);
    }
    const last = steps[steps.length - 1];
    if (last && !last.mate) {
      const f = await pool.analyse(last.after, depth);
      const yours = 100 - coach.winPct(f.score); // the opponent is to move
      if (yours < need(tags)) {
        const mine = f.score.mate !== undefined ? `mate in ${Math.abs(f.score.mate)} ${f.score.mate < 0 ? 'for you' : 'against you'}` : `${-f.score.cp > 0 ? '+' : '−'}${Math.abs(f.score.cp / 100).toFixed(1)} for you`;
        issues.push(`final position: your winning chance is ${yours.toFixed(0)}% (${mine}), below the ${need(tags)}% this kind of puzzle needs`);
      }
    }
    return { id, rating, tags, solver, ok: !issues.length, issues, depth };
  }

  await Promise.all(list.map(async (p) => {
    results.push(await check(p, DEPTH));
    if (++done % 1000 === 0) console.log(`  ${done} of ${list.length}`);
  }));
  // Second look, deeper, at everything the first pass flagged.
  const first = results.filter((r) => !r.ok);
  console.log(`first pass flagged ${first.length}; checking them again at depth ${DEEP}…`);
  const byId = new Map(list.map((p) => [p[0], p]));
  await Promise.all(first.map(async (r) => {
    const again = await check(byId.get(r.id), DEEP);
    r.firstIssues = r.issues;
    r.ok = again.ok;
    r.issues = again.issues;
    r.depth = DEEP;
  }));
  pool.quit();
  const bad = results.filter((r) => !r.ok);
  const cleared = first.filter((r) => r.ok).length;
  fs.writeFileSync(path.join(__dirname, '..', 'js', 'puzzles-exclude.js'),
    '// Generated by tools/audit-puzzles.js: puzzles that Stockfish could not confirm, even at depth ' + DEEP + '.\n' +
    '// Puzzles mode skips them.\nwindow.MYCHESS_PUZZLE_EXCLUDE = ' + JSON.stringify(bad.map((r) => r.id)) + ';\n');
  const seconds = Math.round((Date.now() - t0) / 1000);
  const byTheme = {};
  for (const r of results) for (const t of r.tags) { const b = byTheme[t] || (byTheme[t] = [0, 0]); b[0]++; if (!r.ok) b[1]++; }
  fs.writeFileSync(path.join(__dirname, '..', 'research', 'puzzle-audit.json'), JSON.stringify({ depth: DEPTH, deep: DEEP, seconds, checked: results.length, firstPass: first.length, cleared, removed: bad }, null, 1));
  let md = `# Puzzle audit\n\nGenerated by \`node tools/audit-puzzles.js\` with Stockfish 19 (the build MyChess uses) at depth ${DEPTH}, in ${seconds} seconds. Raw results: \`research/puzzle-audit.json\`.\n\n`;
  md += 'Every puzzle comes from the Lichess puzzle database (CC0). Lichess generates puzzles from real games with Stockfish, then keeps only the ones that millions of attempts and votes rate well; MyChess keeps only highly rated, often-played puzzles (popularity 85+, 300+ plays). This audit repeats the engine check on the copy in the app.\n\n';
  md += `## Result\n\n- **Puzzles checked:** ${results.length}, at depth ${DEPTH}\n- **Confirmed on the first pass:** ${results.length - first.length}\n- **Flagged, then confirmed by a deeper search (depth ${DEEP}):** ${cleared}\n- **Still not confirmed, so removed from the app:** ${bad.length} (listed in \`js/puzzles-exclude.js\`)\n- **Puzzles you can play:** ${results.length - bad.length} (${((100 * (results.length - bad.length)) / results.length).toFixed(2)}% of the set)\n\n`;
  md += 'A puzzle is confirmed when each of your moves is Stockfish’s choice (or just as good: the same mate, or within 2 points of winning chance), and the final position gives you the result the puzzle promises: at least a 35% chance for “equality” puzzles (you save the game), 60% for “advantage” puzzles and 65% for the rest (winning).\n\n';
  if (bad.length) {
    md += '## Removed puzzles\n\n| Puzzle | Rating | Themes | What Stockfish said |\n|---|---|---|---|\n';
    for (const r of bad.slice(0, 200)) md += `| [${r.id}](https://lichess.org/training/${r.id}) | ${r.rating} | ${r.tags.slice(0, 3).join(', ')} | ${r.issues.join('; ')} |\n`;
    if (bad.length > 200) md += `\n…and ${bad.length - 200} more in the JSON file.\n`;
  }
  md += '\n## By theme\n\n| Theme | Puzzles | Flagged |\n|---|---|---|\n';
  for (const [t, [n, f]] of Object.entries(byTheme).sort((a, b) => b[1][0] - a[1][0])) md += `| ${t} | ${n} | ${f} |\n`;
  fs.writeFileSync(path.join(__dirname, '..', 'PUZZLE-AUDIT.md'), md);
  console.log(`checked ${results.length}, flagged ${bad.length}, ${seconds} s`);
})();

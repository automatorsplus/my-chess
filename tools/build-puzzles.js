// Builds js/puzzles-data.js from the Lichess puzzle database (CC0, https://database.lichess.org/#puzzles).
// Usage: zstd -dc lichess_db_puzzle.csv.zst | node tools/build-puzzles.js
//
// Keeps a balanced, high-quality selection: for every lesson theme and every
// 100-point rating band, the best-liked puzzles (popularity and number of
// plays), plus a mixed pool per band. Every kept puzzle is replayed with the
// rules engine to make sure all its moves are legal.
const fs = require('fs');
const path = require('path');
const readline = require('readline');
const Core = require('../js/core.js')();

// Same ids as the lessons in js/puzzles.js.
const LESSON_THEMES = [
  'mateIn1', 'hangingPiece', 'fork', 'pin', 'skewer', 'backRankMate', 'mateIn2', 'attackingF2F7',
  'discoveredAttack', 'doubleCheck', 'trappedPiece', 'promotion', 'capturingDefender',
  'sacrifice', 'deflection', 'attraction', 'smotheredMate', 'intermezzo', 'quietMove', 'clearance',
  'xRayAttack', 'interference', 'mateIn3', 'defensiveMove',
  'pawnEndgame', 'rookEndgame', 'advancedPawn', 'zugzwang',
];
const PER_THEME_BAND = 25;
const MIXED_PER_BAND = 250;
const MIN_RATING = 400, MAX_RATING = 2899;

const buckets = new Map(); // key -> array of { score, id }
const rows = new Map(); // id -> parsed row
function offer(key, cap, entry) {
  let b = buckets.get(key);
  if (!b) buckets.set(key, (b = []));
  if (b.length < cap) { b.push(entry); b.sort((x, y) => y.score - x.score); return; }
  if (entry.score > b[b.length - 1].score) { b[b.length - 1] = entry; b.sort((x, y) => y.score - x.score); }
}

let seen = 0, passing = 0;
const rl = readline.createInterface({ input: process.stdin });
rl.on('line', (line) => {
  if (!seen++) return; // header
  const f = line.split(',');
  const [id, fen, moves] = f;
  const rating = +f[3], rd = +f[4], pop = +f[5], plays = +f[6];
  if (pop < 85 || plays < 300 || rd > 90 || rating < MIN_RATING || rating > MAX_RATING) return;
  passing++;
  const themes = f[7].split(' ');
  const band = Math.floor(rating / 100);
  const score = pop + 6 * Math.log10(plays);
  const entry = { score, id };
  let wanted = false;
  const consider = (key, cap) => {
    const b = buckets.get(key);
    if (!b || b.length < cap || score > b[b.length - 1].score) { offer(key, cap, entry); wanted = true; }
  };
  for (const t of themes) if (LESSON_THEMES.includes(t)) consider(`${t}:${band}`, PER_THEME_BAND);
  consider(`mix:${band}`, MIXED_PER_BAND);
  if (wanted && !rows.has(id)) rows.set(id, { id, fen, moves, rating, themes });
});

rl.on('close', () => {
  const chosen = new Set();
  for (const b of buckets.values()) for (const e of b) chosen.add(e.id);

  const themeIndex = new Map();
  const themeList = [];
  const out = [];
  let rejected = 0;
  for (const id of chosen) {
    const r = rows.get(id);
    const pos = new Core.Position(r.fen);
    let ok = true;
    for (const uci of r.moves.split(' ')) {
      const m = pos.moveFromUci(uci);
      if (!m || !pos.make(m)) { ok = false; break; }
    }
    if (!ok) { rejected++; continue; }
    const idx = r.themes.map((t) => {
      if (!themeIndex.has(t)) { themeIndex.set(t, themeList.length); themeList.push(t); }
      return themeIndex.get(t);
    });
    out.push([r.id, r.fen, r.moves, r.rating, idx]);
  }
  out.sort((a, b) => a[3] - b[3]);

  const header = '// Generated by tools/build-puzzles.js from the Lichess puzzle database (CC0-1.0, https://database.lichess.org/#puzzles).\n' +
    '// Each puzzle: [Lichess puzzle id, FEN before the opponent\'s move, moves in UCI (opponent first), rating, theme indexes].\n';
  const body = 'window.MYCHESS_PUZZLES = ' + JSON.stringify({ themes: themeList, puzzles: out }) + ';\n';
  fs.writeFileSync(path.join(__dirname, '..', 'js', 'puzzles-data.js'), header + body);

  const perTheme = {};
  for (const p of out) for (const i of p[4]) perTheme[themeList[i]] = (perTheme[themeList[i]] || 0) + 1;
  console.log(`rows ${seen - 1}, passing quality filter ${passing}, kept ${out.length}, rejected ${rejected}`);
  console.log(LESSON_THEMES.map((t) => `${t}:${perTheme[t] || 0}`).join(' '));
});

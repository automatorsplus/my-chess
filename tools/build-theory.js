// Builds js/theory-data.js (the move sequences behind Theory mode) from the Lichess
// opening list (CC0, https://github.com/lichess-org/chess-openings).
// Usage: node tools/build-theory.js <folder containing a.tsv … e.tsv>
const fs = require('fs');
const path = require('path');
const Core = require('../js/core.js')();

const dir = process.argv[2];
if (!dir) { console.error('usage: node tools/build-theory.js <dir with a.tsv..e.tsv>'); process.exit(1); }

const lines = [];
let bad = 0;
for (const f of ['a', 'b', 'c', 'd', 'e']) {
  const rows = fs.readFileSync(path.join(dir, f + '.tsv'), 'utf8').split('\n').slice(1).filter(Boolean);
  for (const row of rows) {
    const [eco, name, pgn] = row.split('\t');
    const sans = pgn.replace(/\d+\.(\.\.)?/g, ' ').trim().split(/\s+/);
    const pos = new Core.Position();
    const ucis = [];
    for (const san of sans) {
      const m = pos.moveFromSan(san);
      if (!m) break;
      ucis.push(pos.moveToUci(m));
      pos.make(m);
    }
    if (ucis.length !== sans.length) { bad++; console.warn('could not replay:', eco, name, pgn); continue; }
    lines.push([eco, name, ucis.join(' ')]);
  }
}

const header = '// Generated by tools/build-theory.js from the Lichess chess-openings list (CC0-1.0).\n' +
  '// Each line is [ECO code, name, moves in UCI notation from the starting position].\n';
fs.writeFileSync(path.join(__dirname, '..', 'js', 'theory-data.js'), header + 'window.MYCHESS_THEORY = ' + JSON.stringify({ lines }) + ';\n');
console.log(`lines ${lines.length}, failed ${bad}`);

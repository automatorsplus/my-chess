// Builds js/openings-data.js from the Lichess opening list (CC0, https://github.com/lichess-org/chess-openings).
// Usage: node tools/build-openings.js <folder containing a.tsv … e.tsv>
const fs = require('fs');
const path = require('path');
const Core = require('../js/core.js')();

const dir = process.argv[2];
if (!dir) { console.error('usage: node tools/build-openings.js <dir with a.tsv..e.tsv>'); process.exit(1); }

const named = new Map(); // position key -> { eco, name, plies }
const book = new Set(); // every position that occurs on some opening line
let lines = 0, bad = 0;

for (const f of ['a', 'b', 'c', 'd', 'e']) {
  const rows = fs.readFileSync(path.join(dir, f + '.tsv'), 'utf8').split('\n').slice(1).filter(Boolean);
  for (const row of rows) {
    const [eco, name, pgn] = row.split('\t');
    const sans = pgn.replace(/\d+\.(\.\.)?/g, ' ').trim().split(/\s+/);
    const pos = new Core.Position();
    let ok = true;
    for (const san of sans) {
      const m = pos.moveFromSan(san);
      if (!m || !pos.make(m)) { ok = false; break; }
      book.add(pos.key());
    }
    lines++;
    if (!ok) { bad++; console.warn('could not replay:', eco, name, pgn); continue; }
    const key = pos.key();
    const prev = named.get(key);
    // When several names share a position, keep the one reached by the shortest line.
    if (!prev || sans.length < prev.plies) named.set(key, { eco, name, plies: sans.length });
  }
}

// Compact output: named positions carry [eco, name]; other book positions carry 0.
const out = {};
for (const key of book) out[key] = 0;
for (const [key, v] of named) out[key] = [v.eco, v.name];

const header = '// Generated by tools/build-openings.js from the Lichess chess-openings list (CC0-1.0).\n' +
  '// Keys are positions (FEN without move counters); values are [ECO code, name] or 0 for an unnamed book position.\n';
fs.writeFileSync(path.join(__dirname, '..', 'js', 'openings-data.js'), header + 'window.MYCHESS_OPENINGS = ' + JSON.stringify(out) + ';\n');
console.log(`lines ${lines}, failed ${bad}, named positions ${named.size}, book positions ${book.size}`);
